export function faicSearch(q: string): string[] {
  const needle = q.trim().toLowerCase();
  if (!needle) return [...FAIC_INTERVIEWEES];
  return FAIC_INTERVIEWEES.filter((n) => n.toLowerCase().includes(needle));
}

